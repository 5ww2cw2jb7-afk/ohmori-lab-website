(function(){
  'use strict';
  const page=(location.pathname.split('/').pop()||'index.html').replace(/\.html$/,'');
  const values=window.OHMORI_EDITABLE[page]||{};
  const edits=[...document.querySelectorAll('[data-edit-key], [data-edit-placeholder]')];
  function lang(){return document.documentElement.lang==='en'?'en':'ja';}
  function apply(){
    const lng=lang();
    for(const el of edits){
      const key=el.dataset.editKey||el.dataset.editPlaceholder;
      const item=values[key];if(!item || Array.isArray(item))continue;
      const str=item[lng] ?? item.ja ?? item.en;
      if(str===undefined)continue;
      if(el.dataset.editPlaceholder){el.setAttribute('placeholder',str);continue;}
      if(item.mode==='text'||el.tagName==='OPTION'){el.textContent=str;continue;}
      if(item.mode==='html'){el.innerHTML=str;continue;}
      // Use textContent for plain user strings, and HTML only for the few original lines with markup.
      if (/<br\s*\/?\s*>/i.test(str)) el.innerHTML=str;
      else el.textContent=str.replace(/&amp;/g,'&').replace(/&lt;/g,'<').replace(/&gt;/g,'>');
    }
  }
  function restorePublicationEdits(){
    if(page!=='publications'||!Array.isArray(values.PUBLICATION_RECORDS))return;
    if(typeof publicationItems==='undefined')return;
    publicationItems=values.PUBLICATION_RECORDS.map(x=>({...x}));
    if(typeof renderPublications==='function')renderPublications();
  }
  apply(); restorePublicationEdits();
  // Other original scripts update translations on button clicks. Apply editable values last.
  for(const btn of document.querySelectorAll('#ja,#en'))
    btn.addEventListener('click',()=>setTimeout(()=>{apply();if(page==='publications'&&typeof renderPublications==='function')renderPublications();},0));
})();
